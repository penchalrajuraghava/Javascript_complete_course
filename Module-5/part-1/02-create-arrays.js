// Method 1 - Array Literal (Recommended)

const colors = ["Red", "Green", "Blue"];

console.log(colors);

// Method 2 - Array Constructor

const nums = new Array(1, 2, 3, 4);

console.log(nums);

// Empty Array

const employees = [];

console.log(employees);

// Mixed Array

const data = ["Sunny", 26, true, 95000];

console.log(data);

// Nested Array

const matrix = [
  [1, 2],
  [3, 4],
  [5, 6],
];

console.log(matrix);
