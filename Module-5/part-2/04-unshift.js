/*
==========================================================
Topic: unshift()
==========================================================

Definition:
-----------
Adds one or more elements to the beginning of an array.

Returns:
--------
New length.
*/

const cities = ["Delhi", "Mumbai"];

console.log(cities);

cities.unshift("Hyderabad");

console.log(cities);

cities.unshift("Chennai", "Bangalore");

console.log(cities);
