/*
JavaScript Primitive Data Types
*/

// String
let name = "Sunny";

// Number
let salary = 50000;

// Boolean
let isEmployee = true;

// Undefined
let address;

// Null
let mobile = null;

// BigInt
let large = 12345678901234567890n;

// Symbol
let id = Symbol("id");

console.log(typeof name);
console.log(typeof salary);
console.log(typeof isEmployee);
console.log(typeof address);
console.log(typeof mobile);
console.log(typeof large);
console.log(typeof id);
